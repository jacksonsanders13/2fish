// Downloads the open-source skills Fisher uses and writes them into
// src/lib/skills/library.generated.ts so they ship with the app.
// Run: node scripts/vendor-skills.mjs
import { writeFileSync } from "node:fs";

const CM = "https://raw.githubusercontent.com/coreyhaines31/marketingskills/main/skills";
const LS = "https://raw.githubusercontent.com/garrettjsmith/localseoskills/main/skills";
export const SKILLS = {
  "canvas-design": "https://raw.githubusercontent.com/anthropics/skills/main/skills/canvas-design/SKILL.md",
  unslop: "https://raw.githubusercontent.com/heydamir/unslop/main/skills/unslop/SKILL.md",
  image: `${CM}/image/SKILL.md`,
  "ad-creative": `${CM}/ad-creative/SKILL.md`,
  "gbp-optimization": `${LS}/gbp-optimization/SKILL.md`,
  "gbp-posts": `${LS}/gbp-posts/SKILL.md`,
  "review-management": `${LS}/review-management/SKILL.md`,
  "local-schema": `${LS}/local-schema/SKILL.md`,
  "local-keyword-research": `${LS}/local-keyword-research/SKILL.md`,
  "seo-local": "https://raw.githubusercontent.com/AgriciDaniel/claude-seo/main/skills/seo-local/SKILL.md",
  "ai-seo": `${CM}/ai-seo/SKILL.md`,
  offers: `${CM}/offers/SKILL.md`,
  "marketing-psychology": `${CM}/marketing-psychology/SKILL.md`,
  "marketing-ideas": `${CM}/marketing-ideas/SKILL.md`,
  events: `${CM}/events/SKILL.md`,
  "content-strategy": `${CM}/content-strategy/SKILL.md`,
  emails: `${CM}/emails/SKILL.md`,
  sms: `${CM}/sms/SKILL.md`,
  referrals: `${CM}/referrals/SKILL.md`,
};

const out = {};
for (const [name, url] of Object.entries(SKILLS)) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${name}: ${res.status}`);
  out[name] = (await res.text()).replace(/\r\n/g, "\n").trim();
  console.log(name.padEnd(24), out[name].split(/\s+/).length, "words");
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
  .join("\n");
writeFileSync(
  "src/lib/skills/library.generated.ts",
  `// Generated by scripts/vendor-skills.mjs. Don't edit by hand; rerun the script.\n// Each skill's source and license is listed in ./SKILLS.md and ./LICENSES.md.\n\nexport const SKILL_TEXT: Record<string, string> = {\n${body}\n};\n`,
);
